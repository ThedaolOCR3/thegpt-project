"""LLM 호출 전에 먼저 도는 응급 키워드 하드 필터.

⚠️ 중요: 이건 "의료 트리아지 규칙"이 아니라 소프트웨어 엔지니어링 관점의 안전장치다.
아래 키워드 목록은 의료진 자문 없이 만든 예시 뼈대이므로, 운영 반영 전 반드시
의료 자문을 받아 검증할 것.

왜 필요한가: 시스템 프롬프트(prompts/system_prompt.md)의 "# 9. 응급 상황"이 이미
LLM에게 "응급이면 우선 대응하라"고 지시하지만, 이건 LLM이 지시를 실제로 따를
것이라는 가정에 전적으로 의존한다. 여기서는 그 가정과 무관하게, 특정 키워드가
있으면 **LLM을 아예 호출하지 않고** 고정된 안전 응답으로 강제 전환한다 — LLM의
프롬프트 준수 실패(hallucination, 지시 무시)에 대비한 이중 안전장치.
"""

_HIGH_RISK_KEYWORDS = (
    "숨쉬기 힘들", "숨차", "호흡곤란",
    "가슴 통증", "가슴이 아파", "흉통",
    "의식", "쓰러", "실신",
    "심한 출혈", "피를 토", "각혈",
    "경련", "발작",
    "마비", "말이 어눌",
)

EMERGENCY_RESPONSE = (
    "⚠️ 말씀하신 증상은 응급 상황일 가능성을 고려해야 합니다. "
    "증상이 현재 심하게 나타나고 있다면 지체하지 말고 119에 신고하거나 "
    "가까운 응급실을 방문해 주세요."
)


def detect_emergency(text: str) -> bool:
    return any(keyword in text for keyword in _HIGH_RISK_KEYWORDS)
